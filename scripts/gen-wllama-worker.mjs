/**
 * Generate the static wllama worker files shipped with the extension:
 *
 *   dist/firefox/ai-worker.js    — inference worker
 *   dist/firefox/opfs-worker.js  — OPFS download/write utils worker
 *   dist/firefox/wllama.wasm     — single-thread wasm binary
 *
 * Why: Firefox MV3 CSP blocks `new Worker(blob:...)` in extension pages
 * (wllama's default runtime path). Packaged same-origin worker files ARE
 * allowed. This script assembles self-contained workers from wllama's own
 * npm package sources, replicating exactly what ProxyToWorker.moduleInit()
 * builds at runtime:
 *
 *   const RUN_OPTIONS = {...};            // static (was runtime-injected)
 *   <llama-cpp.js verbatim>               // worker protocol
 *   function wModuleInit() { <glue>; }    // glue with first `var Module`
 *                                          // renamed to `var ___Module`
 *
 * The rename trick (from wllama's worker.ts): the emscripten glue opens
 * with `var Module = typeof Module != "undefined" ? Module : {}`. After
 * renaming only the declaration, the ternary still reads the worker-scope
 * `Module` — which llama-cpp.js assigns from getWModuleConfig(RUN_OPTIONS)
 * before calling wModuleInit(). Everything then operates on that config.
 *
 * The main thread drives this worker with wllama's message protocol:
 * module.init → fs.alloc/fs.write → wllama.start → wllama.action (glue).
 *
 * opfs-worker.js: verbatim copy of wllama's OPFS utils worker code (the
 * OPFS_UTILS_WORKER_CODE string in src/workers-code/generated.ts) — used by
 * CacheManager's OPFS backend for model downloads/writes. Self-contained, no
 * bundling needed.
 *
 * Usage: node scripts/gen-wllama-worker.mjs [--out dist/firefox]
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const PKG = path.resolve(__dirname, "../node_modules/@wllama/wllama");

const args = process.argv.slice(2);
let outDir = path.resolve(__dirname, "../dist/firefox");
if (args[0] === "--out") {
  outDir = path.resolve(args[1]);
}

const emscriptenJs = fs.readFileSync(
  path.join(PKG, "src/wasm/wllama.js"),
  "utf8",
);
const llamaCppWorker = fs.readFileSync(
  path.join(PKG, "src/workers-code/llama-cpp.js"),
  "utf8",
);

// JSPI stub for browsers lacking WebAssembly.Suspending/promising (from
// wllama's worker.ts — keeps the import/export tables valid without JSPI).
const JSPI_STUB = `
if (!WebAssembly.Suspending) {
  WebAssembly.Suspending = function (fn) {
    return fn;
  };
  WebAssembly.promising = function (fn) {
    return function (...args) {
      try {
        return Promise.resolve(fn(...args));
      } catch (e) {
        return Promise.reject(e);
      }
    };
  }
}
`;

// Static replacement for wllama's runtime-injected RUN_OPTIONS.
// nbThread=1 → single-thread build (no pthread blob worker needed);
// compat=false → default JSPI+memory64 build.
// The wasm path resolves relative to this worker's own packaged URL.
const RUN_OPTIONS_SNIPPET = `
const RUN_OPTIONS = {
  pathConfig: {
    "wllama.wasm": new URL("wllama.wasm", self.location.href).href,
  },
  nbThread: 1,
  compat: false,
};
`;

// wModuleInit replicates worker.ts's
//   `function wModuleInit() { ${mainModuleCode}; return Module; }`
// where mainModuleCode has its FIRST `var Module` renamed to `var ___Module`
// (only the declaration — the ternary keeps reading the worker-scope Module
// config that llama-cpp.js assigns before calling wModuleInit()).
function wModuleInitSnippet() {
  const renamed = emscriptenJs.replace("var Module=", "var ___Module=");
  if (renamed === emscriptenJs) {
    throw new Error(
      "could not rename `var Module=` in emscripten glue — " +
        "wllama package format changed, regen adapter needed",
    );
  }
  return `
function wModuleInit() {
${JSPI_STUB}
${renamed}
}
`;
}

const BANNER = `\
// AUTO-GENERATED by scripts/gen-wllama-worker.mjs — DO NOT EDIT.
// Static wllama inference worker for nobait (Firefox MV3 CSP requires
// packaged worker files instead of blob: URLs).
`;

function build() {
  const parts = [BANNER, RUN_OPTIONS_SNIPPET, llamaCppWorker, wModuleInitSnippet()];
  return parts.join("\n\n");
}

/** Emit all three static files into `outDir` (created if needed). */
export function emitWllamaWorkers(outDir_) {
  fs.mkdirSync(outDir_, { recursive: true });
  const workerJs = build();
  const out = path.join(outDir_, "ai-worker.js");
  fs.writeFileSync(out, workerJs);

  // Copy the wasm binary next to the worker (locateFile resolves sibling).
  const wasmSrc = path.join(PKG, "src/wasm/wllama.wasm");
  const wasmDst = path.join(outDir_, "wllama.wasm");
  fs.copyFileSync(wasmSrc, wasmDst);

  const kb = (n) => `${(n / 1024).toFixed(0)} KB`;

  // OPFS utils worker — self-contained, copied verbatim from the package
  // (identical to the OPFS_UTILS_WORKER_CODE string).
  const opfsSrc = path.join(PKG, "src/workers-code/opfs-utils.js");
  const opfsDst = path.join(outDir_, "opfs-worker.js");
  fs.copyFileSync(opfsSrc, opfsDst);

  console.log(
    `[gen-wllama-worker] wrote ${out} (${kb(workerJs.length)}) + ${wasmDst} (${kb(fs.statSync(wasmSrc).size)}) + ${opfsDst} (${kb(fs.statSync(opfsSrc).size)})`,
  );
}

// CLI entry: node scripts/gen-wllama-worker.mjs [--out dist/firefox]
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  emitWllamaWorkers(outDir);
}
